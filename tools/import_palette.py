#!/usr/bin/env python3
"""Validate the frozen 108-crayon palette and generate its pure Kotlin representation."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app/src/main/assets/palette/crayons.json"
OUTPUT = ROOT / "coloring-core/src/main/kotlin/com/colorup/core/CrayonPalette.kt"
ID_PATTERN = re.compile(r"[A-Za-z0-9][A-Za-z0-9._:-]{0,79}")
HEX_PATTERN = re.compile(r"#[0-9A-Fa-f]{6}")


def kotlin_string(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def color(value):
    if not isinstance(value, str) or not HEX_PATTERN.fullmatch(value):
        raise ValueError(f"Expected an opaque six-digit palette color: {value!r}")
    return "0xFF" + value[1:].upper() + "L"


def validate(entries):
    if not isinstance(entries, list) or len(entries) != 108:
        raise ValueError("The palette must contain exactly 108 crayons")
    ids, names, solid_colors = set(), set(), set()
    for position, entry in enumerate(entries):
        ident, name, stops = entry["id"], entry["name"], entry["stops"]
        if not isinstance(ident, str) or not ID_PATTERN.fullmatch(ident) or ident in ids:
            raise ValueError("Crayon IDs must be unique safe identifiers")
        if not isinstance(name, str) or not name.strip() or name in names:
            raise ValueError("Crayon names must be nonempty and unique")
        ids.add(ident)
        names.add(name)
        base = color(entry["hex"])
        if not isinstance(stops, list) or (stops and len(stops) not in range(2, 6)):
            raise ValueError("Gradients require a snapshot of two to five opaque stops")
        converted = [color(stop) for stop in stops]
        if not stops:
            expected_id = "solid-ff" + entry["hex"][1:].lower()
            if ident != expected_id or base in solid_colors:
                raise ValueError("Solid IDs must match their unique ARGB values")
            solid_colors.add(base)
        elif base != converted[len(converted) // 2]:
            raise ValueError("A gradient's representative ARGB must be its middle stop")
        solid_count = 5 if position // 6 < 9 else 4
        if bool(stops) != (position % 6 >= solid_count):
            raise ValueError("Preserve the 18 ordered pages of six crayons: 5+1 then 4+2")
    if len(solid_colors) != 81:
        raise ValueError("Expected 81 solid and 27 gradient crayons")


def generate(entries):
    validate(entries)
    lines = ["// Generated by tools/import_palette.py from assets/palette/crayons.json.",
             "package com.colorup.core", "", "fun solidCrayonId(argb: Long): String = \"solid-${argb.toString(16).padStart(8, '0')}\"", "",
             "data class Crayon(", "    val name: String,", "    val argb: Long,",
             "    val id: String = solidCrayonId(argb),", "    val gradientStops: List<Long> = emptyList(),", ")", "",
             "/** Prototype v0.4: 18 pages of 6; 81 opaque solids plus 27 gradient/glitter styles. */",
             "object CrayonPalette {", "    val colors: List<Crayon> = listOf("]
    for index, entry in enumerate(entries):
        if index % 6 == 0:
            lines.append(f"        // Page {index // 6 + 1}.")
        gradient = "listOf(" + ", ".join(color(stop) for stop in entry["stops"]) + ").immutableCopy()" if entry["stops"] else "emptyList()"
        lines.append(f"        Crayon({kotlin_string(entry['name'])}, {color(entry['hex'])}, "
                     f"id = {kotlin_string(entry['id'])}, gradientStops = {gradient}),")
    lines += ["    ).immutableCopy()", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Read-only: verify generated Kotlin matches the palette")
    options = parser.parse_args()
    entries = json.loads(SOURCE.read_text())
    code = generate(entries)
    if options.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != code:
            raise ValueError("Generated palette is stale; run python3 tools/import_palette.py")
    else:
        OUTPUT.write_text(code)
    print(f"Palette {'verified' if options.check else 'generated'}: 108 stable IDs, 81 solids, 27 gradients, 18 ordered pages.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, TypeError, OSError) as error:
        print(str(error), file=sys.stderr)
        raise SystemExit(1)
